#!/usr/bin/env bash
# Builds a fake "parent" repo whose modules are git submodules, mirroring the
# work project's layout, so Delilah's workspaces can be developed and tested
# without access to the real repos.
#
# Usage: scripts/make-fixture-parent.sh [target-dir]   (default: ./fixtures/parent-env)
#
# Result:
#   <target>/remotes/<name>.git   bare repos acting as GitHub
#   <target>/parent               the parent checkout, submodules initialised
set -euo pipefail

TARGET="${1:-$(cd "$(dirname "$0")/.." && pwd)/fixtures/parent-env}"
MODULES=(svc-payments svc-orders svc-billing common-lib)

# Submodules over file:// are blocked by default since git 2.38.
git_local() { git -c protocol.file.allow=always "$@"; }

if [[ -e "$TARGET" ]]; then
  echo "Already exists: $TARGET (delete it to regenerate)" >&2
  exit 1
fi
mkdir -p "$TARGET/remotes" "$TARGET/seed"

commit_all() {
  git -C "$1" add -A
  git -C "$1" -c user.name="Fixture Bot" -c user.email="fixture@delilah.invalid" \
    commit -q -m "$2"
}

seed_module() {
  local name="$1" dir="$TARGET/seed/$1"
  mkdir -p "$dir/src" "$dir/tests"
  git -C "$dir" init -q -b main

  cat > "$dir/README.md" <<EOF
# $name

Fake module generated by make-fixture-parent.sh.
EOF
  cat > "$dir/src/service.sh" <<'EOF'
#!/usr/bin/env bash
# Toy "service": prints the retry delays for N attempts (base 200 ms, x2).
attempts="${1:-3}"
delay=200
for ((i = 1; i <= attempts; i++)); do
  echo "$delay"
  delay=$((delay * 2))
done
EOF
  cat > "$dir/tests/test.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
out="$(bash "$here/src/service.sh" 3 | tr '\n' ' ')"
[[ "$out" == "200 400 800 " ]] || { echo "FAIL: got '$out'"; exit 1; }
echo "OK"
EOF
  chmod +x "$dir/src/service.sh" "$dir/tests/test.sh"
  commit_all "$dir" "Initial $name"

  git clone -q --bare "$dir" "$TARGET/remotes/$name.git"
}

for m in "${MODULES[@]}"; do seed_module "$m"; done

# Parent repo, also published as a bare remote.
seed_parent="$TARGET/seed/parent"
mkdir -p "$seed_parent"
git -C "$seed_parent" init -q -b main
cat > "$seed_parent/README.md" <<'EOF'
# parent

Fake parent repo: every module is a git submodule.
EOF
for m in "${MODULES[@]}"; do
  git_local -C "$seed_parent" submodule add -q "$TARGET/remotes/$m.git" "$m"
done
commit_all "$seed_parent" "Add modules as submodules"
git clone -q --bare "$seed_parent" "$TARGET/remotes/parent.git"

# Working checkout, as a developer would have it.
git_local clone -q --recurse-submodules "$TARGET/remotes/parent.git" "$TARGET/parent"
rm -rf "$TARGET/seed"

echo "Fixture ready:"
echo "  parent:  $TARGET/parent"
echo "  remotes: $TARGET/remotes"
git -C "$TARGET/parent" submodule status
